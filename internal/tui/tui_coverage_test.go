func sampleReport(t *testing.T) Report {
	t.Helper()
	root := t.TempDir()
	modified := time.Date(2026, 8, 14, 8, 0, 0, 0, time.UTC)
	return scanner.Report{
		Root: root,
		Candidates: []scanner.Candidate{
			{
				Path: filepath.Join(root, "repo-b", "node_modules"), Bytes: 20,
				CategoryKey: "node-modules", Description: "reinstall dependencies",
				ModifiedAt: modified, IsDir: true,
			},
			{
				Path: filepath.Join(root, "repo-a", "cache.pyc"), Bytes: 10,
				CategoryKey: "python-bytecode", Description: "regenerated bytecode",
				ModifiedAt: modified.Add(time.Hour), IsDir: false,
			},
		},
	}
}

func TestBuildSelectionTreeBuildsAndSortsContext(t *testing.T) {
	report := sampleReport(t)
	roots := buildSelectionTree(report)
	if len(roots) != 2 {
		t.Fatalf("expected two roots, got %#v", roots)
	}
	if roots[0].label != "repo-b" || roots[0].bytes != 20 || roots[0].candidateCount != 1 {
		t.Fatalf("unexpected first root: %#v", roots[0])
	}
	leaf := roots[0].children[0]
	if leaf.kind != nodeCandidate || leaf.cand == nil || leaf.parent != roots[0] {
		t.Fatalf("unexpected candidate leaf: %#v", leaf)
	}
	if got := buildSelectionTree(Report{Root: report.Root}); len(got) != 0 {
		t.Fatalf("empty report produced roots: %#v", got)
	}
}

