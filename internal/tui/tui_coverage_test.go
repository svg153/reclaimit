func TestDescribeNodeAndColors(t *testing.T) {
	modified := time.Date(2026, 8, 14, 8, 30, 0, 0, time.UTC)
	selected := makeLeaf("/root/cache.pyc", 1024, true)
	selected.modifiedAt = modified
	selected.cand = &Candidate{
		CategoryKey: "python-bytecode", Description: "regenerated", IsDir: false,
	}
	if got := describeNode(selected); !strings.Contains(got, "file") || !strings.Contains(got, "regenerated") {
		t.Fatalf("unexpected file description: %q", got)
	}
	if nodeColor(selected) != tcell.ColorMediumPurple {
		t.Fatalf("unexpected selected file color")
	}
	selected.selected = false
	if nodeColor(selected) != tcell.ColorSlateGray {
		t.Fatalf("unexpected unselected file color")
	}

	dir := makeLeaf("/root/node_modules", 10, true)
	dir.cand = &Candidate{CategoryKey: "node-modules", IsDir: true}
	if !strings.Contains(describeNode(dir), "directory") || nodeColor(dir) != tcell.ColorTurquoise {
		t.Fatalf("unexpected directory candidate presentation")
	}

	folder := makeFolder("/root/repo", makeLeaf("/root/repo/a", 1, true), makeLeaf("/root/repo/b", 1, false))
	folder.bytes, folder.candidateCount, folder.modifiedAt = 2, 2, modified
	if got := describeNode(folder); !strings.Contains(got, "Context folder") || !strings.Contains(got, "partially selected") {
		t.Fatalf("unexpected folder description: %q", got)
	}
	if nodeColor(folder) != tcell.ColorLightSkyBlue {
		t.Fatalf("unexpected partial folder color")
	}
	toggleSelection(folder, true)
	if nodeColor(folder) != tcell.ColorDeepSkyBlue {
		t.Fatalf("unexpected selected folder color")
	}
	toggleSelection(folder, false)
	if nodeColor(folder) != tcell.ColorSlateGray {
		t.Fatalf("unexpected disabled folder color")
	}
}

func TestTreeNavigationHelpers(t *testing.T) {
	root := tview.NewTreeNode("root")
	child := tview.NewTreeNode("child")
	grandchild := tview.NewTreeNode("grandchild")
	child.AddChild(grandchild)
	root.AddChild(child)
	if firstSelectableTreeNode(root) != child {
		t.Fatal("expected first child")
	}
	if firstSelectableTreeNode(tview.NewTreeNode("empty")).GetText() != "empty" {
		t.Fatal("empty root should be returned")
	}
	if findParentTreeNode(root, grandchild) != child || findParentTreeNode(root, child) != root {
		t.Fatal("parent lookup failed")
	}
	if findParentTreeNode(nil, child) != nil || findParentTreeNode(root, nil) != nil {
		t.Fatal("nil parent lookup should return nil")
	}
	if findParentTreeNode(root, tview.NewTreeNode("missing")) != nil {
		t.Fatal("missing node should not have a parent")
	}
}

func TestRunWithSimulationScreenSavesSelection(t *testing.T) {
	report := sampleReport(t)
	events := []*tcell.EventKey{
		tcell.NewEventKey(tcell.KeyRight, 0, tcell.ModNone),
		tcell.NewEventKey(tcell.KeyLeft, 0, tcell.ModNone),
		tcell.NewEventKey(tcell.KeyEnter, 0, tcell.ModNone),
		tcell.NewEventKey(tcell.KeyRune, ' ', tcell.ModNone),
		tcell.NewEventKey(tcell.KeyRune, 'a', tcell.ModNone),
		tcell.NewEventKey(tcell.KeyRune, 'j', tcell.ModNone),
		tcell.NewEventKey(tcell.KeyRune, 'k', tcell.ModNone),
		tcell.NewEventKey(tcell.KeyRune, 'l', tcell.ModNone),
		tcell.NewEventKey(tcell.KeyRune, 'h', tcell.ModNone),
		tcell.NewEventKey(tcell.KeyRune, 'q', tcell.ModNone),
	}
	selection := runSimulation(t, report, events...)
	if !selection.Saved {
		t.Fatalf("q should save the selection: %#v", selection)
	}
}

func TestRunWithSimulationScreenCancels(t *testing.T) {
	selection := runSimulation(t, sampleReport(t), tcell.NewEventKey(tcell.KeyEscape, 0, tcell.ModNone))
	if selection.Saved {
		t.Fatalf("escape should not save: %#v", selection)
	}
}

func runSimulation(t *testing.T, report Report, events ...*tcell.EventKey) Selection {
	t.Helper()
	screen := tcell.NewSimulationScreen("UTF-8")
	if err := screen.Init(); err != nil {
		t.Fatalf("init simulation screen: %v", err)
	}
	screen.SetSize(120, 40)
	t.Cleanup(screen.Fini)
	app := tview.NewApplication().SetScreen(screen)
	type runResult struct {
		selection Selection
		err       error
	}
	result := make(chan runResult, 1)
	go func() {
		selection, err := runWithApplication(report, app)
		result <- runResult{selection: selection, err: err}
	}()

	ready := make(chan struct{})
	app.QueueUpdateDraw(func() {
		close(ready)
	})
	select {
	case <-ready:
	case <-time.After(2 * time.Second):
		app.Stop()
		t.Fatal("TUI did not become ready")
	}
	for _, event := range events {
		if err := screen.PostEvent(event); err != nil {
			t.Fatalf("post event: %v", err)
		}
	}
	select {
	case got := <-result:
		if got.err != nil {
			t.Fatalf("run TUI: %v", got.err)
		}
		return got.selection
	case <-time.After(2 * time.Second):
		app.Stop()
		t.Fatal("TUI did not stop after input")
		return Selection{}
	}
}
