func TestTreeNodeRenderingAndRefresh(t *testing.T) {
	report := sampleReport(t)
	model := buildSelectionTree(report)[0]
	model.label = "  repo-b  "
	treeNode := buildTreeNode(model)
	if treeNode.GetReference() != model || len(treeNode.GetChildren()) != 1 {
		t.Fatalf("tree node does not preserve model: %#v", treeNode)
	}
	if model.label != "repo-b" {
		t.Fatalf("nodeTreeRef did not trim label: %q", model.label)
	}

	before := treeNode.GetText()
	toggleSelection(model, false)
	refreshTreeNodes(treeNode)
	after := treeNode.GetText()
	if before == after || !strings.Contains(after, "○") {
		t.Fatalf("tree refresh did not update selection: before=%q after=%q", before, after)
	}
}

func TestRenderNodeLabelCoversFolderDirectoryAndFile(t *testing.T) {
	folder := makeFolder("/root/folder", makeLeaf("/root/folder/file", 1, true))
	folder.bytes, folder.candidateCount = 1024, 1
	if got := renderNodeLabel(folder); !strings.Contains(got, "📁") || !strings.Contains(got, "1.0 KiB") {
		t.Fatalf("unexpected folder label: %q", got)
	}

	dirCandidate := makeLeaf("/root/node_modules", 2048, true)
	dirCandidate.cand = &Candidate{CategoryKey: "node-modules", IsDir: true}
	if got := renderNodeLabel(dirCandidate); !strings.Contains(got, "🧹") || !strings.Contains(got, "node-modules") {
		t.Fatalf("unexpected directory label: %q", got)
	}

	fileCandidate := makeLeaf("/root/cache.pyc", 10, true)
	fileCandidate.cand = &Candidate{CategoryKey: "python-bytecode", IsDir: false}
	if got := renderNodeLabel(fileCandidate); !strings.Contains(got, "📄") {
		t.Fatalf("unexpected file label: %q", got)
	}
}

